def d(code, art):
    rows=[r for r in art.split('\n') if r and all(c in '#.' for c in r)]
    assert len(rows)==8, f"{hex(code)} has {len(rows)} rows"
    for r in rows: assert len(r)==8, f"{hex(code)} row width {len(r)}"
    G[code]=rows

